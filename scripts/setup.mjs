import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { parseEnv } from 'node:util';
import { connectionUrl, isMainModule, roles, root, validateConfig } from './config.mjs';

export async function prepareEnvironment(directory = root) {
  const target = new URL('.env', directory);
  let original;
  try { original = await readFile(target, 'utf8'); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    original = await readFile(new URL('.env.example', directory), 'utf8');
  }
  let content = original;
  const existing = parseEnv(content);
  const defaults = parseEnv(await readFile(new URL('.env.example', directory), 'utf8'));
  for (const [key, fallback] of Object.entries(defaults)) {
    if (existing[key]) continue;
    const value = key.endsWith('_PASSWORD') ? randomBytes(32).toString('base64url') : fallback;
    const line = `${key}=${value}`;
    const pattern = new RegExp(`^${key}\\s*=.*$`, 'm');
    content = pattern.test(content) ? content.replace(pattern, line) : `${content.trimEnd()}\n${line}\n`;
  }
  const config = validateConfig(parseEnv(content));
  if (content !== original || !(await readFile(target).catch(() => undefined))) {
    await writeFile(target, content, { mode: 0o600 });
  }
  await mkdir(new URL('generated/', directory), { recursive: true, mode: 0o700 });
  for (const role of roles) {
    for (const docker of [false, true]) {
      const text = `# Generated by npm run setup; contains credentials, do not commit.\nRABBITMQ_URL=${connectionUrl(config, role, docker)}\nRABBIT_RETRY_DELAY_MS=5000\nRABBITMQ_NETWORK=${config.network}\n`;
      await writeFile(new URL(`generated/${role}.${docker ? 'docker' : 'host'}.env`, directory), text, { mode: 0o600 });
    }
  }
  return config;
}

// This file is a CLI; exported setup is also used by the configuration tests.
if (isMainModule(import.meta)) {
  prepareEnvironment().then(() => console.log('Prepared .env and 8 service connection files in generated/; existing passwords were preserved.'))
    .catch(error => { console.error(error.message); process.exitCode = 1; });
}
